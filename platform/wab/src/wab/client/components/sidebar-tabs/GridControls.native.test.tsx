import "@/wab/client/components/sidebar/MixinControls";
import { fakeStudioCtx } from "@/wab/client/__testonly__/fake-init-ctx";
import { GridControls } from "@/wab/client/components/sidebar-tabs/GridControls";
import { SingleRsExpsProvider, StyleComponent, StyleComponentContext, TplExpsProvider } from "@/wab/client/components/style-controls/StyleComponent";
import { AppCtxContext } from "@/wab/client/contexts/AppContexts";
import { StudioCtxContext } from "@/wab/client/contexts/StudioContexts";
import { ViewCtx } from "@/wab/client/studio-ctx/view-ctx";
import { mkMixinPropRef, mkStyleToken, mkTokenRef } from "@/wab/commons/StyleToken";
import { mkArenaFrame, mkMixedArena } from "@/wab/shared/Arenas";
import { RuleSetHelpers } from "@/wab/shared/RuleSetHelpers";
import type { PkgVersionInfoMeta } from "@/wab/shared/SharedApi";
import { TplMgr } from "@/wab/shared/TplMgr";
import { ensure } from "@/wab/shared/common";
import { ComponentType } from "@/wab/shared/core/components";
import { createSite } from "@/wab/shared/core/sites";
import { mkRuleSet } from "@/wab/shared/core/styles";
import { Mixin, VariantedRuleSet, VariantedValue } from "@/wab/shared/model/classes";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import React from "react";
import { mock } from "vitest-mock-extended";

afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it("updates actual Grid controls from original base-only mixin/token references, preserves picker edits and closes retained old providers", async () => {
  vi.spyOn(ViewCtx.prototype, "isVisible").mockReturnValue(false);
  vi.spyOn(ViewCtx.prototype, "scheduleSync").mockImplementation(() => undefined);
  vi.spyOn(ViewCtx.prototype, "awaitSync").mockResolvedValue(undefined);
  const site = createSite(), manager = new TplMgr({ site });
  const component = manager.addComponent({ name: "Grid", type: ComponentType.Plain });
  const group = manager.createGlobalVariantGroup("Grid theme"), dark = manager.createGlobalVariant(group, "Dark");
  const token = mkStyleToken({ name: "Columns", type: "Spacing", value: "repeat(2, minmax(0, 1fr))" });
  token.variantedValues.push(new VariantedValue({ variants: [dark], value: "repeat(7, minmax(0, 1fr))" }));
  const mixinRs = mkRuleSet({ values: {} }), alternate = mkRuleSet({ values: {} });
  new RuleSetHelpers(mixinRs, "div").set("grid-template-columns", mkTokenRef(token));
  new RuleSetHelpers(alternate, "div").set("grid-template-columns", "repeat(8, minmax(0, 1fr))");
  const mixin = new Mixin({ name: "Grid template", uuid: "grid-template-mixin", rs: mixinRs, forTheme: false, preview: undefined, variantedRs: [new VariantedRuleSet({ variants: [dark], rs: alternate })] });
  site.mixins.push(mixin); site.styleTokens.push(token);
  const rs = ensure(site.activeTheme, "Grid theme").defaultStyle.rs, exp = new RuleSetHelpers(rs, "div");
  exp.set("display", "grid"); exp.set("grid-template-columns", mkMixinPropRef(mixin, "grid-template-columns", false));
  const frame = mkArenaFrame({ site, component, name: "Grid", width: 600, height: 200 }); site.arenas.push(mkMixedArena("Grid", [frame]));
  const f = fakeStudioCtx({ site, initialUrl: "/projects/test?arena_type=custom&arena=Grid", devFlagOverrides: { ccStubs: true } });
  await waitFor(() => expect(f.studioCtx.initialRouteReady).toBe(true));
  const studio = f.studioCtx, view = ensure(studio.tryGetViewCtxForFrame(frame), "Grid view");
  studio.setStudioFocusOnViewCtxContent(view); view.setStudioFocusByTpl(component.tplTree);
  const context = new SingleRsExpsProvider(rs, exp, studio, [], { kind: "ruleSet", rs, forTag: "div" });
  const propsProvider = new TplExpsProvider(view, component.tplTree), styling = new StyleComponent({ expsProvider: context });
  const panel = () => <AppCtxContext.Provider value={f.appCtx}><StudioCtxContext.Provider value={studio}><StyleComponentContext.Provider value={styling}><GridControls expsProvider={propsProvider} /></StyleComponentContext.Provider></StudioCtxContext.Provider></AppCtxContext.Provider>;
  const mounted = render(panel());
  try {
    expect(screen.getByDisplayValue("2")).toBeTruthy();
    await act(async () => { await studio.changeUnsafe(() => { view.globalFrame.setTargetVariants([dark]); }); });
    expect(screen.getByDisplayValue("2")).toBeTruthy(); expect(screen.queryByDisplayValue("7")).toBeNull(); expect(screen.queryByDisplayValue("8")).toBeNull();
    await act(async () => { await studio.changeUnsafe(() => { token.value = "repeat(3, minmax(0, 1fr))"; }); });
    const columns = screen.getByDisplayValue("3"); fireEvent.change(columns, { target: { value: "4" } }); fireEvent.keyDown(columns, { key: "Enter" });
    await waitFor(() => expect(exp.getRaw("grid-template-columns")).toBe("repeat(4, minmax(0, 1fr))"));
    expect(token.value).toBe("repeat(3, minmax(0, 1fr))"); expect(new RuleSetHelpers(mixin.rs, "div").getRaw("grid-template-columns")).toBe(mkTokenRef(token));
    fireEvent.click(screen.getByRole("button", { name: "Filled" }));
    await waitFor(() => expect(exp.getRaw("grid-template-columns")).toBe("repeat(auto-fill, minmax(200px, 1fr))"));
    const width = screen.getByDisplayValue("200px"); fireEvent.change(width, { target: { value: "240px" } }); fireEvent.keyDown(width, { key: "Enter" });
    await waitFor(() => expect(exp.getRaw("grid-template-columns")).toBe("repeat(auto-fill, minmax(240px, 1fr))"));
    const release = mock<PkgVersionInfoMeta>({ id: "grid-ui-world", pkgId: "grid-ui-pkg", version: "1.0.0", branchId: null });
    f.api.getPkgVersion.mockResolvedValueOnce({ pkg: { ...release, model: studio.bundleSite().site }, depPkgs: [], etag: "grid-ui-etag" });
    await act(async () => { await studio["loadVersion"](release, true); });
    const fields = vi.spyOn(studio.modelSnapshots, "declaredField"); mounted.rerender(panel());
    expect(fields.mock.calls.some(([model]) => model === rs || model === token || model === mixin || model === component.tplTree)).toBe(false);
    expect(screen.queryByText("Grid Type")).toBeNull();
  } finally { mounted.unmount(); await studio.awaitEval(); studio.dispose(); }
});
