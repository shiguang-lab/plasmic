import "@/wab/client/components/sidebar/MixinControls";
import { fakeStudioCtx } from "@/wab/client/__testonly__/fake-init-ctx";
import { FilterEffectsPanelSection } from "@/wab/client/components/sidebar-tabs/FilterEffectSection";
import { InteractionStylesPanelSection } from "@/wab/client/components/sidebar-tabs/InteractionStylesPanelSection";
import { AppearanceCard } from "@/wab/client/components/style-controls/AppearanceCard";
import { StyleTarget, StyleTargetContext, TplExpsProvider } from "@/wab/client/components/style-controls/StyleComponent";
import { AppContext } from "@/wab/client/components/top-view";
import { AppCtxContext } from "@/wab/client/contexts/AppContexts";
import { StudioCtxContext } from "@/wab/client/contexts/StudioContexts";
import { ViewCtx } from "@/wab/client/studio-ctx/view-ctx";
import { mkArenaFrame, mkMixedArena } from "@/wab/shared/Arenas";
import { RuleSetHelpers } from "@/wab/shared/RuleSetHelpers";
import { TplMgr } from "@/wab/shared/TplMgr";
import { ensureVariantSetting, mkVariant } from "@/wab/shared/Variants";
import { ensure } from "@/wab/shared/common";
import { ComponentType } from "@/wab/shared/core/components";
import { createSite } from "@/wab/shared/core/sites";
import { act, cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import React from "react";

afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("edits inherited chains on the target variant, restores None and migrates interaction/blend controls", async () => {
  vi.spyOn(ViewCtx.prototype, "isVisible").mockReturnValue(false);
  vi.spyOn(ViewCtx.prototype, "scheduleSync").mockImplementation(() => undefined);
  vi.spyOn(ViewCtx.prototype, "awaitSync").mockResolvedValue(undefined);
  vi.stubGlobal("IntersectionObserver", class { observe = vi.fn(); unobserve = vi.fn(); disconnect = vi.fn(); });
  const site = createSite(), manager = new TplMgr({ site });
  const component = manager.addComponent({ name: "Effects", type: ComponentType.Plain });
  const root = component.tplTree, variant = mkVariant({ name: "Active" }); component.variants.push(variant);
  const base = new RuleSetHelpers(root.vsettings[0].rs, "div");
  const target = new RuleSetHelpers(ensureVariantSetting(root, [variant]).rs, "div");
  base.set("filter", "blur(2px) brightness(120%)"); base.set("backdrop-filter", "blur(6px)"); base.set("box-shadow", "0px 4px 16px #000000");
  const frame = mkArenaFrame({ site, component, name: "Effects", width: 400, height: 200 }); site.arenas.push(mkMixedArena("Effects", [frame]));
  const { studioCtx: studio, appCtx } = fakeStudioCtx({ site, initialUrl: "/projects/test?arena_type=custom&arena=Effects" });
  await waitFor(() => expect(studio.initialRouteReady).toBe(true));
  const view = ensure(studio.tryGetViewCtxForFrame(frame), "Effects view");
  studio.setStudioFocusOnViewCtxContent(view); view.setStudioFocusByTpl(root);
  await waitFor(() => expect(studio.isSelectionPending).toBe(false));
  await act(async () => { await studio.changeUnsafe(() => view.currentComponentStackFrame().setTargetVariants([variant])); });
  const provider = new TplExpsProvider(view, root), styling = new StyleTarget({ expsProvider: provider });
  const wrap = (node: React.ReactNode) => <AppContext.Provider value={studio.app}><AppCtxContext.Provider value={appCtx}><StudioCtxContext.Provider value={studio}><StyleTargetContext.Provider value={styling}>{node}</StyleTargetContext.Provider></StudioCtxContext.Provider></AppCtxContext.Provider></AppContext.Provider>;
  const mounted = render(wrap(<><AppearanceCard expsProvider={provider} /><InteractionStylesPanelSection expsProvider={provider} /><FilterEffectsPanelSection expsProvider={provider} /></>));
  try {
    fireEvent.keyDown(screen.getByRole("button", { name: "Layer filter: Blur" }), { key: "ArrowDown", altKey: true });
    await waitFor(() => expect(target.getRaw("filter")).toBe("brightness(120%) blur(2px)"));
    expect(base.getRaw("filter")).toBe("blur(2px) brightness(120%)");
    expect(target.has("backdrop-filter")).toBe(false);
    fireEvent.click(screen.getByRole("button", { name: "Layer filter: Blur" }));
    fireEvent.click(await screen.findByRole("button", { name: "Effect type" }));
    fireEvent.click(await screen.findByRole("option", { name: "None" }));
    await waitFor(() => expect(target.getRaw("filter")).toBe("none"));
    expect(screen.getByRole("dialog", { name: "Layer filter" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Layer filter: Brightness" })).toBeNull();
    fireEvent.click(screen.getByRole("button", { name: "Remove None override" }));
    await waitFor(() => expect(target.has("filter")).toBe(false));
    expect(screen.getByRole("button", { name: "Layer filter: Brightness" })).toBeTruthy();
    const blurRow = ensure(screen.getByRole("button", { name: "Layer filter: Blur" }).closest<HTMLElement>(".list-box-item"), "Blur row");
    fireEvent.click(within(blurRow).getByRole("button", { name: "Remove" }));
    await waitFor(() => expect(target.getRaw("filter")).toBe("brightness(120%)"));
    const brightnessRow = ensure(screen.getByRole("button", { name: "Layer filter: Brightness" }).closest<HTMLElement>(".list-box-item"), "Brightness row");
    fireEvent.click(within(brightnessRow).getByRole("button", { name: "Remove" }));
    await waitFor(() => expect(target.has("filter")).toBe(false));
    expect(base.getRaw("filter")).toBe("blur(2px) brightness(120%)");
    expect(screen.getByRole("button", { name: "Layer filter: Blur" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Layer filter: None" })).toBeNull();
    fireEvent.click(screen.getByRole("button", { name: "Pointer events" }));
    await waitFor(() => expect(target.getRaw("pointer-events")).toBe("none"));
    fireEvent.click(screen.getByRole("button", { name: "Blend mode" }));
    fireEvent.click(await screen.findByRole("switch", { name: "Isolate blending" }));
    await waitFor(() => expect(target.getRaw("isolation")).toBe("isolate"));
    expect(base.getRaw("box-shadow")).toBe("0px 4px 16px #000000");
    expect(target.has("box-shadow")).toBe(false);
    mounted.rerender(wrap(<FilterEffectsPanelSection expsProvider={provider} />));
    expect(screen.queryByText("Interactions")).toBeNull();
    expect(screen.getByRole("button", { name: "Backdrop filter: Blur" })).toBeTruthy();
  } finally { mounted.unmount(); await studio.awaitEval(); studio.dispose(); }
});
