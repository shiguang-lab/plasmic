import { useVariantPickerInputs } from "@/wab/client/components/sidebar-tabs/variant-picker-inputs";
import { ModelSnapshots } from "@/wab/client/studio-ctx/model-snapshots";
import type { StudioCtx } from "@/wab/client/studio-ctx/StudioCtx";
import type { ViewCtx } from "@/wab/client/studio-ctx/view-ctx";
import { TplMgr } from "@/wab/shared/TplMgr";
import { mkArenaFrame } from "@/wab/shared/Arenas";
import { mkVariant, ensureBaseVariantSetting } from "@/wab/shared/Variants";
import { mkParam } from "@/wab/shared/core/lang";
import { typeFactory } from "@/wab/shared/model/model-util";
import { ComponentType } from "@/wab/shared/core/components";
import { mkTplComponent, mkTplTagX, deepTrackComponents } from "@/wab/shared/core/tpls";
import { ChangeRecorder } from "@/wab/shared/core/observable-model";
import { createSite } from "@/wab/shared/core/sites";
import { instUtil } from "@/wab/shared/model/InstUtil";
import { Arg, VariantsRef, CustomCode } from "@/wab/shared/model/classes";
import { createStore } from "zustand/vanilla";
import { act, renderHook } from "@testing-library/react";

it("isolates group values while tracking inherited arguments, owner contracts and replaced expressions", () => {
  const site = createSite(), models = new ModelSnapshots(), lifetime = new AbortController();
  const manager = new TplMgr({ site });
  const owner = manager.addComponent({ name: "Owner", type: ComponentType.Plain });
  const component = manager.addComponent({ name: "Child", type: ComponentType.Plain });
  const groups = ["Mode", "Size"].map(name => manager.createVariantGroup({ component, name }));
  groups.forEach(group => { group.variants = [mkVariant({ name: "First", parent: group }), mkVariant({ name: "Second", parent: group })]; });
  const tpl = mkTplComponent(component, owner.variants[0]);
  owner.tplTree = mkTplTagX("div", { baseVariant: owner.variants[0] }, [tpl]);
  const expr = new VariantsRef({ variants: [groups[0].variants[0]] });
  const arg = new Arg({ param: groups[0].param, expr });
  ensureBaseVariantSetting(tpl).args = [arg];
  deepTrackComponents(site);
  const studio = { site, modelSnapshots: models, arenaState: { lifetime: () => lifetime.signal, store: createStore(() => ({})) } } as unknown as StudioCtx;
  const frame = mkArenaFrame({ site, component: owner, name: "Owner", width: 800, height: 600 });
  const view = { studioCtx: studio, site, modelLifetime: lifetime.signal, disposeSignal: lifetime.signal, isDisposed: false, arenaFrame: () => frame } as unknown as ViewCtx;
  const recorder = new ChangeRecorder({ inst: site, _instUtil: instUtil });
  const edit = (run: () => void) => act(() => models.sync(recorder.withRecording(run).changes));
  const first = renderHook(() => useVariantPickerInputs(view, tpl, groups[0]));
  const second = renderHook(() => useVariantPickerInputs(view, tpl, groups[1]));
  try {
    const unchanged = second.result.current, before = first.result.current;
    edit(() => { groups[0].variants[0].name = "Renamed"; });
    expect(first.result.current).not.toBe(before); expect(second.result.current).toBe(unchanged);
    const named = first.result.current;
    edit(() => { arg.expr = new CustomCode({ code: "(enabled)", fallback: expr }); });
    expect(first.result.current).not.toBe(named); expect(second.result.current).toBe(unchanged);
    const dynamic = first.result.current;
    edit(() => { expr.variants = [groups[0].variants[1]]; });
    expect(first.result.current).not.toBe(dynamic);
    edit(() => { ensureBaseVariantSetting(tpl).args = []; });
    const removed = first.result.current;
    edit(() => { expr.variants = []; });
    expect(first.result.current).toBe(removed);
    const beforeOwner = second.result.current;
    edit(() => { owner.params.push(mkParam({ name: "LinkedMode", type: typeFactory.text(), paramType: "prop" })); });
    expect(second.result.current).not.toBe(beforeOwner);
    act(() => lifetime.abort());
    expect(first.result.current).toEqual([]); expect(second.result.current).toEqual([]);
  } finally { first.unmount(); second.unmount(); lifetime.abort(); recorder.dispose(); models.dispose(); }
});
