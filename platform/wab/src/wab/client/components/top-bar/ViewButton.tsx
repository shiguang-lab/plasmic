import styles from "./ViewButton.module.less";
import popupStyles from "../ui/EditorPopup.module.less";
import { useStudioOverlayState } from "@/wab/client/studio-ctx/studio-overlay-state";
import { useStudioRenderPolicy } from "@/wab/client/studio-ctx/studio-render-policy";
import { useStudioArena } from "@/wab/client/studio-ctx/arena-state";
import { useShallow } from "zustand/react/shallow";
import { useStore } from "zustand";
import { useStudioSelection } from "@/wab/client/studio-ctx/selection-state";
import { runEditorViewMenuAction } from "@/wab/client/components/top-bar/editor-view-menu";
import {
  DefaultViewButtonProps,
  PlasmicViewButton,
} from "@/wab/client/plasmic/plasmic_kit_top_bar/PlasmicViewButton";
import { useI18n } from "@/wab/client/i18n";
import { UiText } from "@/wab/client/i18n/UiText";
// This is a skeleton starter React component generated by Plasmic.
// This file is owned by you, feel free to edit as you see fit.

import {
  MenuBuilder,
  TextAndShortcut,
} from "@/wab/client/components/menu-builder";
import { IFrameAwareDropdownMenu } from "@/wab/client/components/widgets";
import { TriggerTarget } from "@/wab/client/components/widgets/TriggerAnchor";
import { useStudioCtx } from "@/wab/client/contexts/StudioContexts";
import { getComboForAction } from "@/wab/client/shortcuts/studio/studio-shortcuts";
import { DEVFLAGS } from "@/wab/shared/devflags";
import {
  BorderOutlined,
  ColumnHeightOutlined,
  CommentOutlined,
  ControlOutlined,
  EditOutlined,
  EyeInvisibleOutlined,
  EyeOutlined,
  ReloadOutlined,
} from "@ant-design/icons";
import { Menu, Tooltip } from "antd";
import * as React from "react";

type ViewButtonProps = DefaultViewButtonProps;

const contentCreatorModeHelp = (
  <>
    <div>
      <UiText
        message={
          "Content creator mode simplifies the UI and limits edits to ensure design consistency."
        }
      />
    </div>
    <div className="mt-sm">
      <UiText
        message={
          "It limits insertion to existing components in this project and hides style settings and most design panels."
        }
      />
    </div>
    <div className="mt-sm">
      <UiText
        message={
          "Users with content creator roles always use content creator mode."
        }
      />
    </div>
  </>
);

const ViewButton = React.memo(function ViewButton(props: ViewButtonProps) {
  const { t } = useI18n();

  const studioCtx = useStudioCtx();
  const { kind: arenaKind, focusedMode: isFocusedMode } = useStudioArena(
    studioCtx, useShallow((state) => ({ kind: state.kind, focusedMode: state.focusedMode })),
  );
  const [showSlotPlaceholder, showContainerPlaceholder, fullPageHeight, isAutoOpenMode] =
    useStudioRenderPolicy(
      studioCtx,
      useShallow((state) => [
        state.showSlotPlaceholder,
        state.showContainerPlaceholder,
        state.fullPageHeight,
        state.autoOpen,
      ] as const),
    );
  const contentEditorMode = useStore(
    studioCtx.uiEnvironment.store,
    (state) => state.contentEditorMode,
  );
  useStudioSelection(studioCtx, (state) => state.view);
  const vc = studioCtx.focusedViewCtx();
  const showMultiplayerSelections = useStudioOverlayState(studioCtx, (state) => state.multiplayerSelections);
  const showAncestorsHoverBoxes = useStudioOverlayState(studioCtx, (state) => state.ancestorsHoverBoxes);
  const showCommentsOverlay = useStudioOverlayState(studioCtx, (state) => state.commentsOverlay);

  return (
    <IFrameAwareDropdownMenu
      overlayClassName={`${popupStyles.root} ${styles.popup}`}
      menu={() => {
        const builder = new MenuBuilder();
        builder.genSection(undefined, (push) => {
          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(studioCtx, "toggleShowSlotPlaceholder")
              }
              key="toggle-show-slot-placeholder"
            >
              {showSlotPlaceholder ? <EyeInvisibleOutlined /> : <EyeOutlined />}
              {t(
                showSlotPlaceholder
                  ? "Hide placeholders for empty slots"
                  : "Show placeholders for empty slots",
              )}
            </Menu.Item>,
          );
          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(
                  studioCtx,
                  "toggleShowContainerPlaceholder",
                )
              }
              key="toggle-show-container-placeholder"
            >
              {showContainerPlaceholder ? (
                <EyeInvisibleOutlined />
              ) : (
                <EyeOutlined />
              )}
              {t(
                showContainerPlaceholder
                  ? "Hide placeholders for empty containers"
                  : "Show placeholders for empty containers",
              )}
            </Menu.Item>,
          );
          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(
                  studioCtx,
                  "toggleShowMultiplayerSelections",
                )
              }
              key="toggle-show-multiplayer"
            >
              {showMultiplayerSelections ? (
                <EyeInvisibleOutlined />
              ) : (
                <EyeOutlined />
              )}
              {t(
                showMultiplayerSelections
                  ? "Hide cursors and selections from other users"
                  : "Show cursors and selections from other users",
              )}
            </Menu.Item>,
          );
          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(
                  studioCtx,
                  "toggleShowAncestorsHoverBoxes",
                )
              }
              key="toggle-show-ancestors-hover-boxes"
            >
              {showAncestorsHoverBoxes ? (
                <EyeInvisibleOutlined />
              ) : (
                <EyeOutlined />
              )}
              {t(
                showAncestorsHoverBoxes
                  ? "Hide container outlines when hovering"
                  : "Show container outlines when hovering",
              )}
            </Menu.Item>,
          );

          if (vc) {
            const isOutlineMode = vc.canvasCtx.isOutlineMode();
            push(
              <Menu.Item
                onClick={async () =>
                  runEditorViewMenuAction(studioCtx, "toggleOutlineMode")
                }
                key="toggle-show-outline"
              >
                <BorderOutlined />
                <TextAndShortcut shortcut={getComboForAction("OUTLINE_MODE")}>
                  {t(isOutlineMode ? "Hide outline mode" : "Show outline mode")}
                </TextAndShortcut>
              </Menu.Item>,
            );
          }

          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(studioCtx, "toggleFullPageHeight")
              }
              key="toggle-full-page-height"
            >
              <ColumnHeightOutlined />
              <TextAndShortcut
                shortcut={getComboForAction("TOGGLE_FULL_PAGE_HEIGHT")}
              >
                {t(
                  fullPageHeight
                    ? "Fit to viewport height"
                    : "Show full page height",
                )}
              </TextAndShortcut>
            </Menu.Item>,
          );
        });
        builder.genSection(undefined, (push) => {
          if (isFocusedMode || arenaKind === "component" || arenaKind === "page") {
            push(
              <Menu.Item
                onClick={async () =>
                  runEditorViewMenuAction(studioCtx, "toggleFocusedMode")
                }
                key="toggle-focus-mode"
              >
                <EditOutlined />
                <TextAndShortcut
                  shortcut={getComboForAction("TOGGLE_FOCUSED_MODE")}
                >
                  {t(
                    isFocusedMode
                      ? "Turn on design mode"
                      : "Turn off design mode",
                  )}
                </TextAndShortcut>
              </Menu.Item>,
            );
          }

          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(studioCtx, "toggleAutoOpenMode")
              }
              key="toggle-auto-open-mode"
            >
              <ControlOutlined />
              {t(
                isAutoOpenMode
                  ? "Turn off auto-open mode"
                  : "Turn on auto-open mode",
              )}
            </Menu.Item>,
          );

          if (studioCtx.showComments()) {
            push(
              <Menu.Item
                onClick={async () =>
                  runEditorViewMenuAction(
                    studioCtx,
                    "toggleShowCommentsOverlay",
                  )
                }
                key="toggle-show-comments-overlay"
              >
                <CommentOutlined />
                {t(
                  showCommentsOverlay
                    ? "Hide comments overlay"
                    : "Show comments overlay",
                )}
              </Menu.Item>,
            );
          }

          const canChangeContentEditorMode =
            !studioCtx.isContentEditor() && !DEVFLAGS.contentEditorMode;
          if (canChangeContentEditorMode) {
            push(
              <Menu.Item
                onClick={async () =>
                  runEditorViewMenuAction(
                    studioCtx,
                    "toggleContentEditorMode",
                  )
                }
                key="toggle-content-editor-mode"
              >
                <EditOutlined />
                <Tooltip zIndex={200000} title={contentCreatorModeHelp}>
                  <TriggerTarget>
                    {t(
                      contentEditorMode
                        ? "Turn off content creator mode"
                        : "Turn on content creator mode",
                    )}
                  </TriggerTarget>
                </Tooltip>
              </Menu.Item>,
            );
          }
        });
        builder.genSection(undefined, (push) => {
          push(
            <Menu.Item
              onClick={async () =>
                runEditorViewMenuAction(studioCtx, "refreshData")
              }
              key="refresh-data"
            >
              <ReloadOutlined />
              {t("Refresh data")}
            </Menu.Item>,
          );
        });

        return builder.build({
          menuName: "view-menu",
        });
      }}
    >
      <PlasmicViewButton root={{ props: { "aria-label": t("View") } }} {...props} />
    </IFrameAwareDropdownMenu>
  );
});

export default ViewButton;
