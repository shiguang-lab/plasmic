import { fakeStudioCtx } from "@/wab/client/__testonly__/fake-init-ctx";
import { CanvasNavigationLinks } from "@/wab/client/components/canvas/CanvasNavigationLinks";
import { ViewCtx } from "@/wab/client/studio-ctx/view-ctx";
import { mkArenaFrame, mkMixedArena } from "@/wab/shared/Arenas";
import { TplMgr } from "@/wab/shared/TplMgr";
import { ensure } from "@/wab/shared/common";
import { ComponentType } from "@/wab/shared/core/components";
import { code, codeLit } from "@/wab/shared/core/exprs";
import { createSite } from "@/wab/shared/core/sites";
import { mkInteraction } from "@/wab/shared/core/states";
import { Pt } from "@/wab/shared/geom";
import { EventHandler, ensureKnownTplTag } from "@/wab/shared/model/classes";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import $ from "jquery";
import * as React from "react";

afterEach(() => { cleanup(); vi.restoreAllMocks(); });

it("follows element scroll and frame movement, updates navigation, removes one action with undo, and retires its view", async () => {
  vi.spyOn(ViewCtx.prototype, "isVisible").mockReturnValue(false);
  vi.spyOn(ViewCtx.prototype, "scheduleSync").mockImplementation(() => undefined);
  vi.spyOn(ViewCtx.prototype, "awaitSync").mockResolvedValue(undefined);
  const site = createSite(), manager = new TplMgr({ site });
  const source = manager.addComponent({ name: "List", type: ComponentType.Page });
  const target = manager.addComponent({ name: "Detail", type: ComponentType.Page });
  ensure(target.pageMeta, "Target page metadata").path = "/detail";
  const tpl = ensureKnownTplTag(source.tplTree);
  const handler = new EventHandler({ interactions: [] });
  const save = mkInteraction(handler, "customFunction", "Save", {});
  const navigate = mkInteraction(handler, "navigation", "Open", { destination: codeLit("/detail") });
  handler.interactions.push(save, navigate);
  tpl.vsettings[0].attrs.onClick = handler;
  tpl.vsettings[0].attrs.href = code("$state.destination");
  const frames = [source, target].map((component, index) => mkArenaFrame({ site, component, name: component.name, width: 400, height: 700, left: index * 640, top: 0 }));
  site.arenas.push(mkMixedArena("Navigation", frames));
  const { studioCtx: studio } = fakeStudioCtx({ site, initialUrl: "/projects/test?arena_type=custom&arena=Navigation" });
  await waitFor(() => expect(studio.initialRouteReady).toBe(true));
  const scaler = document.body.appendChild(document.createElement("div"));
  scaler.className = "canvas-editor__scaler";
  let dragOffset = 0, headerTop = -96;
  const views = frames.map((frame) => {
    const view = ensure(studio.tryGetViewCtxForFrame(frame), "Navigation artboard view");
    vi.spyOn(view.initialRenderReadyStore, "getState").mockReturnValue(true);
    ensure(view.csEvaluator, "Canvas evaluator").renderStatusStore.setState({ renderCount: 1 });
    const container = scaler.appendChild(document.createElement("div"));
    const iframe = container.appendChild(document.createElement("iframe"));
    vi.spyOn(iframe, "getBoundingClientRect").mockImplementation(() => new DOMRect((frame.left ?? 0) + (frame === frames[1] ? dragOffset : 0), frame.top ?? 0, frame.width, frame.height));
    const header = container.appendChild(document.createElement("div"));
    header.className = "CanvasFrame__Label";
    vi.spyOn(header, "getBoundingClientRect").mockImplementation(() => new DOMRect((frame.left ?? 0) + (frame === frames[1] ? dragOffset : 0), (frame.top ?? 0) + headerTop, frame.width, -headerTop - 16));
    view.canvasCtx.$viewport = () => $(iframe);
    view.canvasCtx.$doc = () => $(ensure(iframe.contentDocument, "Artboard document"));
    return view;
  });
  const view = views[0], doc = view.canvasCtx.$doc()[0];
  studio.viewportCtx = view.viewportCtx;
  vi.spyOn(studio.viewportCtx, "canvasPadding").mockReturnValue(Pt.zero());
  const element = doc.body.appendChild(doc.createElement("a"));
  let top = 120;
  Object.defineProperty(element, "offsetWidth", { value: 80 });
  vi.spyOn(element, "getBoundingClientRect").mockImplementation(() => new DOMRect(300, top, 80, 40));
  vi.spyOn(view, "maybeDomsForTpl").mockReturnValue([null, [element]]);
  const canvasPointer = vi.fn();
  const mounted = render(<div ref={(node) => { node?.addEventListener("pointerdown", canvasPointer); }}><CanvasNavigationLinks studioCtx={studio} /></div>);
  const path = () => screen.getByRole("button", { name: "Click → Detail" });
  try {
    await waitFor(() => expect(path().getAttribute("d")).toContain("M 380 140"));
    expect(screen.queryByRole("button", { name: /Dynamic navigation/ })).toBeNull();
    const visiblePath = ensure(document.querySelector('path[marker-end]'), "Visible connection");
    expect(visiblePath.getAttribute("stroke-width")).toBe("1");
    expect(visiblePath.getAttribute("vector-effect")).toBe("non-scaling-stroke");
    expect(document.querySelector('[data-test-id="canvas-navigation-links"] rect')).toBeNull();
    top = 220;
    fireEvent.scroll(doc);
    await waitFor(() => expect(path().getAttribute("d")).toContain("M 380 240"));
    await act(async () => { await studio.changeUnsafe(() => { frames[1].left = 900; }); });
    expect(frames[1].left).toBe(900);
    expect(studio.modelSnapshots.field(frames[1], "left").getState()).toBe(900);
    await waitFor(() => expect(path().getAttribute("d")).toContain("900 240"));
    dragOffset = 60;
    const destinationContainer = ensure(views[1].canvasCtx.$viewport()[0].parentElement, "Destination container");
    destinationContainer.style.transform = "translateX(60px)";
    await waitFor(() => expect(path().getAttribute("d")).toContain("960 240"));
    expect(frames[1].left).toBe(900);
    let transforming = true;
    const transformingSpy = vi.spyOn(studio.viewportCtx, "isTransforming").mockImplementation(() => transforming);
    const scaleSpy = vi.spyOn(studio.viewportCtx, "scale").mockReturnValue(2);
    const stablePath = path().getAttribute("d");
    dragOffset = 120;
    destinationContainer.style.transform = "translateX(120px)";
    await act(async () => { await new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))); });
    expect(path().getAttribute("d")).toBe(stablePath);
    scaleSpy.mockRestore();
    transforming = false;
    await waitFor(() => expect(path().getAttribute("d")).toContain("1020 240"));
    transformingSpy.mockRestore();
    dragOffset = 60;
    destinationContainer.style.transform = "translateX(60px)";
    await waitFor(() => expect(path().getAttribute("d")).toContain("960 240"));
    // A newly visible device shell becomes the destination boundary.
    const shell = destinationContainer.appendChild(document.createElement("div"));
    shell.setAttribute("data-test-id", "device-frame");
    vi.spyOn(shell, "getBoundingClientRect").mockReturnValue(new DOMRect(948, -32, 424, 764));
    await waitFor(() => expect(path().getAttribute("d")).toContain("948 240"));
    shell.remove();
    await waitFor(() => expect(path().getAttribute("d")).toContain("960 240"));
    await act(async () => { await studio.changeUnsafe(() => { frames[1].left = -700; }); });
    await waitFor(() => expect(path().getAttribute("d")).toContain("-152"));
    headerTop = -160;
    const header = ensure(view.canvasCtx.$viewport()[0].parentElement?.querySelector(".CanvasFrame__Label"), "Source title");
    header.setAttribute("style", "top: -160px");
    await waitFor(() => expect(path().getAttribute("d")).toContain("-216"));
    await act(async () => { await studio.changeUnsafe(() => { frames[1].left = 900; }); });
    await waitFor(() => expect(path().getAttribute("d")).toContain("960 240"));
    await act(async () => { await studio.changeUnsafe(() => { target.name = "Updated detail"; }); });
    await waitFor(() => expect(screen.getByRole("button", { name: "Click → Updated detail" })).toBeTruthy());
    fireEvent.click(screen.getByRole("button", { name: "Click → Updated detail" }));
    expect(screen.queryByRole("button", { name: "Edit navigation" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Locate target" })).toBeNull();
    const removeButton = await screen.findByRole("button", { name: "Remove navigation" });
    fireEvent.pointerDown(removeButton);
    expect(canvasPointer).not.toHaveBeenCalled();
    fireEvent.mouseDown(removeButton);
    fireEvent.mouseUp(removeButton);
    fireEvent.click(removeButton);
    await waitFor(() => expect(handler.interactions).toEqual([save]));
    await waitFor(() => expect(document.querySelector('path[role="button"]')).toBeNull());
    await act(async () => { await studio.undo(); });
    await waitFor(() => expect(handler.interactions).toHaveLength(2));
    await waitFor(() => expect(screen.getByRole("button", { name: "Click → Updated detail" })).toBeTruthy());
    await act(async () => { await studio.changeUnsafe(() => { handler.interactions.splice(0, 1); }); });
    fireEvent.click(screen.getByRole("button", { name: "Click → Updated detail" }));
    fireEvent.click(await screen.findByRole("button", { name: "Remove navigation" }));
    await waitFor(() => expect(tpl.vsettings[0].attrs.onClick).toBeUndefined());
    await waitFor(() => expect(document.querySelector('path[role="button"]')).toBeNull());
    await act(async () => { await studio.undo(); });
    await waitFor(() => expect(tpl.vsettings[0].attrs.onClick).toBe(handler));
    expect(handler.interactions).toEqual([navigate]);
    await waitFor(() => expect(document.querySelector('path[role="button"]')).toBeTruthy());
    act(() => studio.disposeViewCtx(view));
    await waitFor(() => expect(document.querySelector('path[role="button"]')).toBeNull());
    top = 320;
    fireEvent.scroll(doc);
    expect(document.querySelector('path[role="button"]')).toBeNull();
  } finally { mounted.unmount(); scaler.remove(); await studio.awaitEval(); studio.dispose(); }
});

it("anchors repeated source elements to the first visible control instead of their merged midpoint", async () => {
  vi.spyOn(ViewCtx.prototype, "isVisible").mockReturnValue(false);
  vi.spyOn(ViewCtx.prototype, "scheduleSync").mockImplementation(() => undefined);
  vi.spyOn(ViewCtx.prototype, "awaitSync").mockResolvedValue(undefined);
  const site = createSite(), manager = new TplMgr({ site });
  const source = manager.addComponent({ name: "Cards", type: ComponentType.Page });
  const target = manager.addComponent({ name: "Detail", type: ComponentType.Page });
  ensure(target.pageMeta, "Target page metadata").path = "/detail";
  const tpl = ensureKnownTplTag(source.tplTree);
  const handler = new EventHandler({ interactions: [] });
  handler.interactions.push(mkInteraction(handler, "navigation", "Open", { destination: codeLit("/detail") }));
  tpl.vsettings[0].attrs.onClick = handler;
  const frames = [source, target].map((component, index) => mkArenaFrame({ site, component, name: component.name, width: 400, height: 700, left: index * 640, top: 0 }));
  site.arenas.push(mkMixedArena("RepeatedNavigation", frames));
  const { studioCtx: studio } = fakeStudioCtx({ site, initialUrl: "/projects/test?arena_type=custom&arena=RepeatedNavigation" });
  await waitFor(() => expect(studio.initialRouteReady).toBe(true));
  const scaler = document.body.appendChild(document.createElement("div"));
  scaler.className = "canvas-editor__scaler";
  const views = frames.map((frame) => {
    const view = ensure(studio.tryGetViewCtxForFrame(frame), "Navigation artboard view");
    vi.spyOn(view.initialRenderReadyStore, "getState").mockReturnValue(true);
    ensure(view.csEvaluator, "Canvas evaluator").renderStatusStore.setState({ renderCount: 1 });
    const container = scaler.appendChild(document.createElement("div"));
    const iframe = container.appendChild(document.createElement("iframe"));
    vi.spyOn(iframe, "getBoundingClientRect").mockImplementation(() => new DOMRect(frame.left ?? 0, frame.top ?? 0, frame.width, frame.height));
    view.canvasCtx.$viewport = () => $(iframe);
    view.canvasCtx.$doc = () => $(ensure(iframe.contentDocument, "Artboard document"));
    return view;
  });
  const view = views[0], doc = view.canvasCtx.$doc()[0];
  studio.viewportCtx = view.viewportCtx;
  vi.spyOn(studio.viewportCtx, "canvasPadding").mockReturnValue(Pt.zero());
  const firstCard = doc.body.appendChild(doc.createElement("div"));
  const secondCard = doc.body.appendChild(doc.createElement("div"));
  const firstButton = firstCard.appendChild(doc.createElement("button"));
  const secondButton = secondCard.appendChild(doc.createElement("button"));
  Object.defineProperty(firstButton, "offsetWidth", { value: 80, configurable: true });
  Object.defineProperty(secondButton, "offsetWidth", { value: 80, configurable: true });
  vi.spyOn(firstButton, "getBoundingClientRect").mockReturnValue(new DOMRect(300, 120, 80, 40));
  vi.spyOn(secondButton, "getBoundingClientRect").mockReturnValue(new DOMRect(300, 420, 80, 40));
  vi.spyOn(view, "maybeDomsForTpl").mockReturnValue([null, [firstButton, secondButton]]);
  const mounted = render(<CanvasNavigationLinks studioCtx={studio} />);
  const path = () => screen.getByRole("button", { name: "Click → Detail" });
  try {
    await waitFor(() => expect(path().getAttribute("d")).toContain("M 380 140"));
    expect(path().getAttribute("d")).not.toContain("M 380 290");
    // When the first instance has no visible layout box, fall back to the next visible button.
    Object.defineProperty(firstButton, "offsetWidth", { value: 0, configurable: true });
    vi.spyOn(firstButton, "getBoundingClientRect").mockReturnValue(new DOMRect(0, 0, 0, 0));
    fireEvent.scroll(doc);
    await waitFor(() => expect(path().getAttribute("d")).toContain("M 380 440"));
  } finally { mounted.unmount(); scaler.remove(); await studio.awaitEval(); studio.dispose(); }
});
