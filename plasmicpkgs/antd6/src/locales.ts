export type AntdLocale = keyof typeof localePacks;

// Locale packs can be wrapped in a default export by CJS/ESM interop.
function normalizeLocale(locale: Locale | { default: Locale }): Locale {
  return "default" in locale ? locale.default : locale;
}

export const antdLocales = Object.fromEntries(
  Object.entries(localePacks).map(([key, locale]) => [key, normalizeLocale(locale)]),
) as Record<AntdLocale, Locale>;
