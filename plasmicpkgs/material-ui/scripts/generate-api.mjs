// Material UI's MIT-licensed API metadata, pinned to the installed release.
import { readFile, writeFile } from "node:fs/promises";
const pkg = JSON.parse(
  await readFile(new URL("../package.json", import.meta.url)),
);
const base = `https://raw.githubusercontent.com/mui/material-ui/v${pkg.dependencies["@mui/material"]}/docs/`;
export const sections = {
  Inputs:
    "Autocomplete Button ButtonGroup Checkbox Fab FormControl FormControlLabel FormGroup FormHelperText FormLabel IconButton Input InputAdornment InputBase InputLabel MenuItem NativeSelect OutlinedInput Radio RadioGroup Rating Select Slider Switch TextField ToggleButton ToggleButtonGroup",
  Navigation:
    "AppBar BottomNavigation BottomNavigationAction Breadcrumbs Drawer Link Menu MenuList MobileStepper Pagination PaginationItem Step StepButton StepConnector StepContent StepLabel Stepper SwipeableDrawer Tab Tabs Toolbar",
  "Data display":
    "Avatar AvatarGroup Badge Chip Divider List ListItem ListItemAvatar ListItemButton ListItemIcon ListItemText ListSubheader SvgIcon Table TableBody TableCell TableContainer TableFooter TableHead TablePagination TableRow TableSortLabel Tooltip Typography",
  Feedback:
    "Alert AlertTitle Backdrop CircularProgress Dialog DialogActions DialogContent DialogContentText DialogTitle LinearProgress Skeleton Snackbar SnackbarContent",
  Surfaces:
    "Accordion AccordionActions AccordionDetails AccordionSummary Card CardActionArea CardActions CardContent CardHeader CardMedia Paper",
  Layout: "Box Container Grid Stack ImageList ImageListItem ImageListItemBar",
};
const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const cache = new Map();
async function load(name) {
  if (!cache.has(name))
    cache.set(
      name,
      (async () => {
        const url = `${base}pages/material-ui/api/${kebab(name)}.json`;
        const response = await fetch(url);
        if (!response.ok) throw new Error(`${url}: ${response.status}`);
        const doc = await response.json();
        const descriptionsResponse = await fetch(
          `${base}translations/api-docs/${kebab(name)}/${kebab(name)}.json`,
        );
        if (!descriptionsResponse.ok)
          throw new Error(`Missing descriptions for ${name}`);
        const descriptions = await descriptionsResponse.json();
        for (const [key, prop] of Object.entries(doc.props)) {
          prop.description = descriptions.propDescriptions[key]?.description;
        }
        const inherited = doc.inheritance?.pathname?.startsWith(
          "/material-ui/api/",
        )
          ? await load(doc.inheritance.component)
          : {};
        return { ...inherited, ...doc.props };
      })(),
    );
  return cache.get(name);
}
const docs = {};
for (const [section, names] of Object.entries(sections)) {
  const list = names.split(" ");
  for (let i = 0; i < list.length; i += 6) {
    await Promise.all(
      list.slice(i, i + 6).map(async (name) => {
        docs[name] = { section, props: await load(name) };
      }),
    );
  }
}
await writeFile(
  new URL("../src/api.json", import.meta.url),
  JSON.stringify(
    Object.fromEntries(
      Object.keys(docs)
        .sort()
        .map((name) => [name, docs[name]]),
    ),
    null,
    2,
  ) + "\n",
);
const native = Object.keys(docs)
  .sort()
  .filter(
    (name) =>
      ![
        "Autocomplete",
        "Dialog",
        "Drawer",
        "SwipeableDrawer",
        "Snackbar",
        "Menu",
        "Popover",
        "Tooltip",
        "Tabs",
        "BottomNavigation",
        "Select",
        "NativeSelect",
        "Accordion",
        "Stepper",
        "StepButton",
      ].includes(name),
  );
const inspectChildren = new Set([
  "FormControl",
  "ImageListItem",
  "Stack",
  "ToggleButtonGroup",
  "ButtonGroup",
  "AvatarGroup",
  "Breadcrumbs",
]);
// These are documented as nodes/unions, but MUI inspects or clones one node.
const singleNodeProps = {
  Checkbox: ["icon", "checkedIcon", "indeterminateIcon"],
  Radio: ["icon", "checkedIcon"],
  Tab: ["icon"],
};
await writeFile(
  new URL("../src/native.ts", import.meta.url),
  '// Generated by scripts/generate-api.mjs.\nimport { withSlots } from "./slots";\n' +
    native
      .map((name) => {
        const single = [
          ...Object.entries(docs[name].props)
            .filter(([, prop]) => prop.type.name === "element")
            .map(([key]) => key),
          ...(singleNodeProps[name] ?? []),
        ];
        return single.length || inspectChildren.has(name)
          ? `import Native${name} from "@mui/material/${name}";\nexport const ${name} = withSlots(Native${name}, ${JSON.stringify(single)}, ${inspectChildren.has(name)});`
          : `export { default as ${name} } from "@mui/material/${name}";`;
      })
      .join("\n") +
    "\n",
);
console.log(`Generated ${Object.keys(docs).length} component APIs`);
